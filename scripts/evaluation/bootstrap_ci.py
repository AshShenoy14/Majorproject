"""
95% bootstrap confidence intervals for the production ensemble (ESM-2 + GraphSAGE + XGBoost) on the test set.

Resamples the committed test-set predictions (ESMGAT/results/final_predictions.csv, column p_graphsage_ensemble)
2,000 times with replacement and reports percentile CIs at the val-selected threshold from
assets/evaluation/final_test_metrics.json. No model is re-run or retrained. Before writing, it checks that the
point estimates on the full test set reproduce final_test_metrics.json.

Output: assets/evaluation/bootstrap_ci.json.   Run from the repo root:  python scripts/evaluation/bootstrap_ci.py
"""
import argparse
import json
import os
import sys

import numpy as np
import pandas as pd
from sklearn.metrics import accuracy_score, average_precision_score, f1_score, precision_score, recall_score, roc_auc_score

sys.path.append(os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..")))
from src.utils.paths import PROJECT_ROOT

ENSEMBLE_KEY = "Full Ensemble (XGBoost)"
METRICS = {
    "accuracy": lambda y, p, t: accuracy_score(y, p >= t),
    "precision": lambda y, p, t: precision_score(y, p >= t, zero_division=0),
    "recall": lambda y, p, t: recall_score(y, p >= t),
    "f1": lambda y, p, t: f1_score(y, p >= t),
    "roc_auc": lambda y, p, t: roc_auc_score(y, p),
    "pr_auc": lambda y, p, t: average_precision_score(y, p),
}


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--n_bootstrap", type=int, default=2000)
    parser.add_argument("--seed", type=int, default=42)
    args = parser.parse_args()

    reference = json.loads((PROJECT_ROOT / "assets" / "evaluation" / "final_test_metrics.json").read_text())
    ref = reference["models"][ENSEMBLE_KEY]
    threshold = float(ref["val_selected_threshold"])

    preds = pd.read_csv(PROJECT_ROOT / "ESMGAT" / "results" / "final_predictions.csv")
    y = preds["label"].to_numpy()
    p = preds["p_graphsage_ensemble"].to_numpy()

    point = {name: float(fn(y, p, threshold)) for name, fn in METRICS.items()}
    mismatched = {k: (point[k], ref[k]) for k in point if abs(point[k] - ref[k]) > 1e-4}
    if mismatched:
        raise SystemExit(f"Point estimates do not reproduce final_test_metrics.json: {mismatched}")

    rng = np.random.default_rng(args.seed)
    samples = {name: [] for name in METRICS}
    n = len(y)
    for _ in range(args.n_bootstrap):
        idx = rng.integers(0, n, n)
        for name, fn in METRICS.items():
            samples[name].append(fn(y[idx], p[idx], threshold))

    out = {
        "description": "Percentile bootstrap over the committed test-set predictions of the production ensemble; "
                       "no model re-run. Generated by scripts/evaluation/bootstrap_ci.py.",
        "model": "ESM-2 (esm2_t30_150M_UR50D) + GraphSAGE + XGBoost",
        "predictions": "ESMGAT/results/final_predictions.csv (p_graphsage_ensemble)",
        "threshold": threshold,
        "n_test": int(n),
        "n_bootstrap": args.n_bootstrap,
        "seed": args.seed,
    }
    for name, vals in samples.items():
        vals = np.array(vals)
        out[name] = {"mean": float(vals.mean()), "ci_lo": float(np.percentile(vals, 2.5)), "ci_hi": float(np.percentile(vals, 97.5))}
    out["point_estimate_reference"] = point

    path = PROJECT_ROOT / "assets" / "evaluation" / "bootstrap_ci.json"
    path.write_text(json.dumps(out, indent=2))
    for name in METRICS:
        print(f"{name:9s} point {point[name]:.4f}  95% CI [{out[name]['ci_lo']:.4f}, {out[name]['ci_hi']:.4f}]")
    print(f"Wrote {path}")


if __name__ == "__main__":
    main()
